def render(result, catalog=None):
    lines = [f"状态：{result['status']}", f"已完成原生试验：{result.get('trials', 0)}",
             f"总耗时：{result.get('wall_seconds', 0):.1f} 秒"]
    best = result.get('best')
    if best:
        lines.append(f"模式：{result['mode']}；距离：{best['distance']}")
        c = best['candidate']
        names = dict(TitanLaser='泰坦级激光', TitanCannon='泰坦级加农炮',
                     TitanShockwaveCannon='冲击波加农炮', TitanShield='泰坦级护盾', TitanArray='泰坦级阵列')
        target_names = {'None': '无', 'Regen': '再生', 'Shielded': '护盾', 'Armored': '装甲',
                        'Unarmored': '无甲', 'Phasing': '相位', "Can't Phase": '无法相位',
                        'Carrier': '航母', 'Barrier': '屏障', 'No Barrier': '无屏障', 'Torpedo': '鱼雷',
                        'Highest Max HP': '最高血量上限', 'Lowest Max HP': '最低血量上限',
                        'Highest HP': '最高血量', 'Lowest HP': '最低血量', 'Highest Damage': '最高伤害',
                        'Closest': '最近', 'Furthest': '最远', 'Keep Target': '锁定', 'Change Target': '转换',
                        'Allow': '集火', 'Avoid': '分散', 'Biggest Cluster': 'Biggest Cluster',
                        'Closest Cluster': 'Closest Cluster'}
        for i, w in enumerate(c['weapons'], 1):
            branches = []
            for threshold, selected in w['milestones'].items():
                if catalog:
                    rows = catalog.milestones(w['id'], w['level'])[threshold]
                    position = next(j for j, row in enumerate(rows, 1) if row['id'] == selected)
                    description = f"选项{position} {catalog.tables['core_milestones'][selected]['name']}"
                else:
                    description = selected
                branches.append(f'{threshold}级={description}')
            targeting = ' / '.join(target_names.get(w['targeting'][k], w['targeting'][k])
                                   for k in ('type', 'priority', 'swapping', 'overlap'))
            lines.append(f"武器槽 {i}：{names[w['id']]} Lv{w['level']}\n  分支：{'; '.join(branches)}\n  目标：{targeting}")
        lines.append(f"护盾：泰坦级护盾 Lv{c['shield']['level']}（固定里程碑自动生效）\n"
                     f"阵列核心：Lv{c['array_core']['level']}；容量 {c['array_capacity']}")
        part_names = {p['id']: f"{ {'DEFENSIVE_PLATING': '防护', 'TURRET_POWER': '炮塔', 'DISRUPTION_FIELD': '干扰场'}.get(p['system'], p['system']) }{p['number']}"
                      for p in result.get('region', {}).get('array_targets', [])}
        for i, e in enumerate(c['sequence'], 1):
            name = catalog.elements[e['id']]['name'] + f" [{e['id']}]" if catalog else e['id']
            targets = ' > '.join(part_names.get(t, t) for t in e['targets'])
            lines.append(f"阵列 {i}：{name} → {targets or '默认目标 / 非攻击技能'}")
        if result['mode'] == 'farm_distance':
            for item in best['validation']:
                b = item['battle']
                lines.append(f"挂机复核 seed={item['seed']}：{b['seconds']:.1f} 秒、{b['colossal_kills']} 次巨型敌人击杀、"
                             f"{b['deaths']} 死亡、最低护盾 {b['minimum_shield_fraction']:.1%}")
        else:
            lines.append(f"实际首领击杀时间：{best['battle']['seconds']:.2f} 秒")
    else:
        lines.append('当前预算内没有完成符合条件的验证；不代表此区域不可击杀或无法挂机。')
    lines.append('原版规则执行的研究结果，尚未与该玩家正式游戏实战对照；不保证全局最优或无限期稳定。')
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description='Independent Titan native joint search')
    parser.add_argument('--source', type=Path, default=default_source(), help='Recovered source; defaults to local/current_source.json')
    parser.add_argument('--godot', type=Path, required=True)
    parser.add_argument('--player', type=Path, required=True)
    parser.add_argument('--sector', required=True)
    parser.add_argument('--layer', choices=LAYERS, required=True)
    parser.add_argument('--mode', choices=('boss_once', 'farm_distance'), required=True)
    parser.add_argument('--budget-seconds', type=float, default=180)
    parser.add_argument('--seed', type=int, default=12345)
    parser.add_argument('--distance-step', type=int, default=20)
    parser.add_argument('--boss-seconds', type=float, default=90)
    parser.add_argument('--farm-seconds', type=float, default=120)
    parser.add_argument('--farm-cycles', type=int, default=10)
    parser.add_argument('--clock', choices=('fixed', 'realtime'), default='fixed')
    parser.add_argument('--label', help='Unique run label; generated by default')
    args = parser.parse_args(argv)
    started = time.perf_counter()
    require(args.source is not None, 'Provide --source or configure local/current_source.json')
    require(0 < args.budget_seconds < float('inf'), 'Budget must be finite and positive')
    require(0 <= args.seed <= 2147483647, 'Seed must be in [0, 2147483647]')
    require(args.distance_step > 0, 'distance-step must be positive')
    require(0 < args.boss_seconds < float('inf'), 'boss-seconds must be finite and positive')
    require(120 <= args.farm_seconds < float('inf') and args.farm_cycles >= 10,
            'Final farm validation cannot be shorter than 120 seconds / 10 cycles')
    require(args.godot.is_file(), 'Godot executable not found')
    catalog = Catalog(args.source)
    player = read_json(args.player)
    profile = prepare_player(catalog, player)
    region = catalog.region(args.sector, args.layer)
    check_access(player, region, args.mode)
    # Catch impossible capacity / core definitions before paying the native startup cost.
    next(Candidates(catalog, profile, region, args.seed).seeds())
    label = args.label or datetime.now().strftime('search_%Y%m%d_%H%M%S_') + uuid.uuid4().hex[:6]
    import re
    require(re.fullmatch(r'[A-Za-z0-9_-]+', label), 'Use a simple unique label')
    output = ROOT / 'results' / label
    require(not output.exists() and not (ROOT / 'work' / label).exists(), 'Run label already exists')
    output.mkdir(parents=True)
    deadline = started + args.budget_seconds
    metadata = dict(mode=args.mode, region=region, game_version=catalog.version, source_sha256=catalog.hashes, player=player,
                    player_sha256=hashlib.sha256(args.player.read_bytes()).hexdigest(),
                    python_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                   for p in (ROOT / 'titan_research').glob('*.py')},
                    godot_sha256=hashlib.sha256(args.godot.read_bytes()).hexdigest(),
                    clock=args.clock, seed=args.seed, budget_seconds=args.budget_seconds,
                    globally_optimal=False, live_game_comparison=False,
                    affordability_checked=False, standard_titan_only=True,
                    output_directory=str(output), native_run_directory=str(ROOT / 'work' / label))
    write_json(output / 'input.json', dict(metadata, normalized_profile=profile))
    print(f'结果目录：{output}\n正在准备隔离原生工程（首次加载通常需要约 60 秒，计入总预算）…', flush=True)
    last_log = [0.0]

    def publish(result):
        result.update(wall_seconds=time.perf_counter() - started)
        write_json(output / 'result.json', {**metadata, **result})
        (output / 'result.txt').write_text(render(result, catalog), encoding='utf-8')
        if time.perf_counter() - last_log[0] >= 10 or result.get('best'):
            print(f"{result['status']} | trials={result.get('trials', 0)} | {result['wall_seconds']:.1f}s", flush=True)
            last_log[0] = time.perf_counter()

    def record(item):
        with (output / 'trials.jsonl').open('a', encoding='utf-8') as stream:
            stream.write(json.dumps(item, ensure_ascii=False, allow_nan=False) + '\n')

    result = dict(status='PREPARING', mode=args.mode, best=None, trials=0)
    publish(result)
    try:
        with NativeWorker(args.source, args.godot, label, deadline, args.clock) as worker:
            write_json(output / 'startup.json', worker.startup)
            result = optimize(catalog, player, profile, region, args.mode, worker, deadline,
                              args.seed, publish, record, args.farm_seconds, args.farm_cycles,
                              args.distance_step, args.boss_seconds)
    except (TimeoutError, KeyboardInterrupt) as error:
        result = read_json(output / 'result.json')
        result.update(status='BUDGET_EXHAUSTED' if isinstance(error, TimeoutError) else 'CANCELLED',
                      stop_reason=str(error) or 'cancelled')
    except Exception as error:
        result = read_json(output / 'result.json')
        result.update(status='ERROR', error=str(error))
        publish(result)
        raise
    publish(result)
    print(render(result, catalog), end='')
    print(f'完整结果：{output / "result.json"}', flush=True)
    return 0 if result.get('best') else 3


def configure(argv=None):
    parser = argparse.ArgumentParser(description='Enter a reusable player profile; no sector is stored')
    parser.add_argument('--source', type=Path, default=default_source())
    parser.add_argument('--output', type=Path, default=ROOT / 'local' / 'player.json')
    args = parser.parse_args(argv)
    require(args.source is not None, 'Provide --source or configure local/current_source.json')
    catalog = Catalog(args.source)
    require(not args.output.exists(), 'Player file exists; edit it directly or choose a new --output')
    require(not args.output.resolve().is_relative_to(catalog.source), 'Output must be outside the source project')
    print(f'录入 {catalog.version} 当前统计总览；先结束临时战斗技能。支持 2.20e20 等科学计数法。')
    layer = input('读数时实际层域 surface / antumbra / penumbra / umbra：').strip()
    stats = {key: float(input(title + '：')) for key, title in (
        ('titan_damage', '统计：泰坦级伤害'), ('titan_max_shields', '统计：泰坦级最大护盾值'),
        ('array_capacity', '统计页阵列容量（保留小数）'))}
    alignment = {key: float(input(title + '校准值：')) for key, title in (('antumbra', '伪本影'), ('penumbra', '半影'))}
    level = int(input('读数时阵列核心等级：'))
    damage = float(input('阵列核心 Base Damage（不是序列顶部合计伤害）：'))
    caps = {}
    for core in ('TitanLaser', 'TitanCannon', 'TitanShockwaveCannon', 'TitanShield', 'TitanArray'):
        value = input(f'{core} 可同时达到的等级（未解锁普通武器留空）：').strip()
        if value:
            caps[core] = int(value)
    highest = {key: int(input(f'本轮 {key} 最高已到达区域（未解锁填 0）：')) for key in LAYERS}
    boundary = int(input('本影域合并边界区域（未解锁填 0）：'))
    answer = input('已解锁再整合？y / n：').strip().lower()
    require(answer in ('y', 'n'), 'Reintegration answer must be y or n')
    reintegration = answer == 'y'
    data = dict(statistics=dict(reference_layer=layer, temporary_combat_effects_active=False,
                               summary_stats=stats, alignment=alignment, reference_array_level=level,
                               reference_array_base_damage=damage, core_level_caps=caps),
                progress=dict(highest_sectors=highest, umbra_sector_number=boundary, reintegration=reintegration))
    if catalog.enemy_alignment:
        data['statistics']['game_version'] = catalog.version
        answer = input('已解锁 Galaxy 12（影响 165+ 敌人缩放）？y / n：').strip().lower()
        require(answer in ('y', 'n'), 'Galaxy 12 answer must be y or n')
        data['progress']['galaxy12_unlocked'] = answer == 'y'
    prepare_player(catalog, data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open('x', encoding='utf-8') as stream:
        json.dump(data, stream, ensure_ascii=False, indent=2, allow_nan=False)
    print(f'已保存玩家参数：{args.output.resolve()}')
    return 0
